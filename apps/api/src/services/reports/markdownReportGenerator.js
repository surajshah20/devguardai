/**
 * Generates a GitHub-Flavored Markdown code review report.
 *
 * @param {object} params
 * @param {object} params.repository - Repository metadata
 * @param {string} params.commitSha - Git commit SHA
 * @param {string} params.targetRef - Branch or tag
 * @param {object} params.summary - Findings count summary
 * @param {Array<object>} params.findings - List of findings
 * @param {object} [params.project] - Project metadata
 * @param {string} [params.aiError] - Note if AI review was skipped or had error
 * @returns {string} Formatted Markdown report
 */
export function generateMarkdownReport({
  repository = {},
  commitSha = 'unknown',
  targetRef = 'main',
  summary = {},
  findings = [],
  project = {},
  aiError,
}) {
  const timestamp = new Date().toUTCString();

  const lines = [
    `# DevGuard AI Code Review Report`,
    ``,
    `> **Automated Code Review & Security Analysis**  `,
    `> Repository: \`${repository.fullName || repository.name || 'Unknown'}\`  `,
    `> Commit SHA: \`${commitSha}\` (Ref: \`${targetRef}\`)  `,
    `> Generated At: \`${timestamp}\``,
    ``,
    `---`,
    ``,
    `## 1. Executive Summary`,
    ``,
    `| Metric | Count |`,
    `| :--- | :--- |`,
    `| **Total Findings** | **${summary.total || findings.length}** |`,
    `| 🔴 **Critical** | ${summary.critical || 0} |`,
    `| 🟠 **High** | ${summary.high || 0} |`,
    `| 🟡 **Medium** | ${summary.medium || 0} |`,
    `| 🔵 **Low** | ${summary.low || 0} |`,
    `| ⚪ **Info** | ${summary.info || 0} |`,
    ``,
    `**Project Ecosystem:** ${project.ecosystem ? project.ecosystem.toUpperCase() : 'Generic'}  `,
    `**Detected Languages:** ${(project.languages || []).join(', ') || 'N/A'}  `,
    `**Frameworks:** ${(project.frameworks || []).join(', ') || 'None detected'}`,
    ``,
  ];

  if (aiError) {
    lines.push(
      `> [!NOTE]`,
      `> **AI Note:** ${aiError}`,
      ``
    );
  }

  lines.push(`---`, ``, `## 2. Findings Detail`, ``);

  if (findings.length === 0) {
    lines.push(`✅ **No issues detected.** The reviewed code passed all static and security checks.`, ``);
  } else {
    for (const [index, f] of findings.entries()) {
      const severityIcon = {
        critical: '🔴 CRITICAL',
        high: '🟠 HIGH',
        medium: '🟡 MEDIUM',
        low: '🔵 LOW',
        info: '⚪ INFO',
      }[f.severity] || f.severity.toUpperCase();

      lines.push(
        `### ${index + 1}. [${severityIcon}] ${f.title}`,
        ``,
        `- **File:** \`${f.filePath}\` (Lines ${f.startLine}–${f.endLine})`,
        `- **Source:** \`${f.source}\` (\`${f.ruleId}\`) | **Confidence:** \`${f.confidence}\` | **Status:** \`${f.verificationStatus}\``,
        ``,
        `**Evidence:**`,
        `\`\`\`text`,
        f.evidence,
        `\`\`\``,
        ``,
        `**Explanation:**  `,
        `${f.explanation}`,
        ``
      );

      if (f.suggestedFix) {
        lines.push(
          `**Suggested Remediation:**  `,
          `${f.suggestedFix}`,
          ``
        );
      }

      lines.push(`---`, ``);
    }
  }

  lines.push(
    `## 3. Review Methodology & Safety Disclaimers`,
    ``,
    `- **Deterministic Findings (\`semgrep\` / \`eslint\`):** Verified static analysis detections against known vulnerability patterns.`,
    `- **AI Findings (\`ai\`):** Contextual suggestions proposed by LLM analysis; marked as \`unverified\` pending human reviewer sign-off.`,
    `- **Non-destructive:** DevGuard never pushes code changes or modifies production branches automatically.`,
    ``,
    `*Report generated by DevGuard AI Agent.*`
  );

  return lines.join('\n');
}

